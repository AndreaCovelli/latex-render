#!/usr/bin/env python3
"""Writes hooks/widths.ts: the terminal column ranges of Unicode characters.

Usage: python3 -I scripts/gen-widths.py hooks/widths.ts

Reads Python's own unicodedata (its version is stamped in the header), so the
output follows the Unicode version of the Python that runs it.
"""
import sys
import unicodedata

ZERO = {'Mn', 'Me'}


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            ch = chr(cp)
            hit = unicodedata.category(ch) not in ZERO and pred(ch)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    body = ', '.join(f'0x{a:x}, 0x{b:x}' for a, b in rs)
    lines, line = [], ''
    for part in body.split(', '):
        if len(line) + len(part) + 2 > 78:
            lines.append(line.rstrip())
            line = ''
        line += part + ', '
    lines.append(line.rstrip().rstrip(','))
    return f'// {doc}\nexport const {name}: readonly number[] = [\n' + '\n'.join('  ' + l for l in lines) + ',\n]\n'


wide = ranges(lambda c: unicodedata.east_asian_width(c) in ('W', 'F'))
amb = ranges(lambda c: unicodedata.east_asian_width(c) == 'A')

out = (
    f'// Generated by scripts/gen-widths.py from Unicode {unicodedata.unidata_version}'
    ' East_Asian_Width. Do not edit by hand.\n'
    '// Each table is a sorted list of inclusive [start, end] code point pairs.\n\n'
    + emit('WIDE', 'Two columns in every terminal (East_Asian_Width W and F).', wide)
    + '\n'
    + emit('AMBIGUOUS', 'One column in most terminals, two where CJK settings widen them (East_Asian_Width A).', amb)
)
with open(sys.argv[1], 'w') as f:
    f.write(out)
print(f'{len(wide)} wide and {len(amb)} ambiguous ranges')
